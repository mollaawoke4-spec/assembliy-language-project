-- ======================
-- STUDENT DEPARTMENT CHOICES (Preferences)
-- ======================
CREATE TABLE student_choices (
    id                  INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    user_id             INT UNSIGNED NOT NULL,
    department_id       INT UNSIGNED NOT NULL,
    choice_order        TINYINT UNSIGNED NOT NULL,   -- 1 = first choice, 2 = second, etc.
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE CASCADE,
    UNIQUE KEY uk_user_choice (user_id, choice_order),
    UNIQUE KEY uk_user_dept (user_id, department_id),
    INDEX idx_user (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ======================
-- ASSIGNMENT RESULTS
-- ======================
CREATE TABLE assignments (
    id                  INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    user_id             INT UNSIGNED NOT NULL UNIQUE,
    department_id       INT UNSIGNED,                 -- NULL if not assigned
    choice_order        TINYINT UNSIGNED,             -- which preference was used
    status              ENUM('Assigned', 'Not Assigned', 'Pending') DEFAULT 'Pending',
    score_used          DECIMAL(8,2),
    remarks             TEXT,
    assigned_at         TIMESTAMP NULL,
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE SET NULL,
    INDEX idx_status (status),
    INDEX idx_dept (department_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
