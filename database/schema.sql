-- Department Selection System - Database Schema
-- Focus: Registration Module + core supporting tables

CREATE DATABASE IF NOT EXISTS department_selection;
USE department_selection;

-- ======================
-- USERS / AUTHENTICATION
-- ======================
CREATE TABLE users (
    id              INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    student_id      VARCHAR(50)  UNIQUE NOT NULL,          -- University Student ID
    email           VARCHAR(150) UNIQUE NOT NULL,
    password_hash   VARCHAR(255) NOT NULL,
    role            ENUM('student', 'admin') DEFAULT 'student',
    is_active       TINYINT(1)   DEFAULT 1,
    created_at      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    
    INDEX idx_student_id (student_id),
    INDEX idx_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ======================
-- STUDENT PERSONAL INFO
-- ======================
CREATE TABLE student_profiles (
    id                  INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    user_id             INT UNSIGNED NOT NULL,
    
    -- Personal Information
    first_name          VARCHAR(100) NOT NULL,
    middle_name         VARCHAR(100),
    last_name           VARCHAR(100) NOT NULL,
    gender              ENUM('Male', 'Female', 'Other') NOT NULL,
    date_of_birth       DATE,
    phone               VARCHAR(20),
    national_id         VARCHAR(50),
    
    -- Address
    region              VARCHAR(100),
    city                VARCHAR(100),
    address             TEXT,
    
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    UNIQUE KEY uk_user_id (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ======================
-- ACADEMIC INFORMATION
-- ======================
CREATE TABLE student_academic (
    id                      INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    user_id                 INT UNSIGNED NOT NULL,
    
    -- High School / Previous Education
    high_school_name        VARCHAR(200),
    high_school_year        YEAR,
    
    -- Scores (adjust according to your university rules)
    total_score             DECIMAL(8,2),           -- Overall entrance / calculated score
    gpa                     DECIMAL(4,2),           -- If applicable
    english_score           DECIMAL(5,2),
    mathematics_score       DECIMAL(5,2),
    science_score           DECIMAL(5,2),
    social_score            DECIMAL(5,2),
    
    -- Category / Quota (common in many universities)
    category                ENUM('Regular', 'Special Needs', 'Regional Quota', 'Other') DEFAULT 'Regular',
    
    -- Additional academic fields (can be extended)
    stream                  VARCHAR(100),           -- e.g. Natural Science, Social Science
    remarks                 TEXT,
    
    created_at              TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    UNIQUE KEY uk_user_id (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

