-- ======================
-- COLLEGES / SCHOOLS
-- ======================
CREATE TABLE colleges (
    id              INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    name            VARCHAR(150) NOT NULL UNIQUE,
    code            VARCHAR(20)  UNIQUE,
    description     TEXT,
    is_active       TINYINT(1) DEFAULT 1,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ======================
-- DEPARTMENTS
-- ======================
CREATE TABLE departments (
    id                      INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    college_id              INT UNSIGNED NOT NULL,
    name                    VARCHAR(150) NOT NULL,
    code                    VARCHAR(20)  UNIQUE,
    description             TEXT,
    
    -- Capacity
    capacity                INT UNSIGNED NOT NULL DEFAULT 0,
    remaining_capacity      INT UNSIGNED NOT NULL DEFAULT 0,  -- Updated during assignment
    
    -- Minimum Requirements
    min_total_score         DECIMAL(8,2) DEFAULT 0,
    min_gpa                 DECIMAL(4,2) DEFAULT 0,
    min_english             DECIMAL(5,2) DEFAULT 0,
    min_mathematics         DECIMAL(5,2) DEFAULT 0,
    min_science             DECIMAL(5,2) DEFAULT 0,
    min_social              DECIMAL(5,2) DEFAULT 0,
    
    -- Stream restriction (NULL = open to all)
    allowed_stream          VARCHAR(100),           -- e.g. 'Natural Science', 'Social Science', NULL
    
    -- Priority / Ranking weight (higher = preferred in ties if needed)
    priority_order          INT DEFAULT 100,
    
    is_active               TINYINT(1) DEFAULT 1,
    created_at              TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    
    FOREIGN KEY (college_id) REFERENCES colleges(id) ON DELETE RESTRICT,
    UNIQUE KEY uk_college_dept (college_id, name),
    INDEX idx_active (is_active),
    INDEX idx_capacity (remaining_capacity)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

